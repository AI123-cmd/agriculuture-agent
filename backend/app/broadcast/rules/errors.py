"""规则层的实现期异常（T3-05，技术方案 11.1）。

与流程配置错误同属"代码/配置缺陷"而非"数据问题"：五段式缺一段、文案模板漏配、级别
闭集被写坏，都属于规则实现写错。抛异常而不是静默跳过该条目，因为静默跳过会让这类
错误长期潜伏——一条规则写错了 `action`，如果只是被跳过，没人会发现它从未生效。

刻意不继承 `AppException`：它是内建缺陷的信号，应在测试与启动自检里直接暴露，
不该被 API 的全局 handler 转成对农户的响应。
"""


class RuleImplementationError(Exception):
    """规则实现错误：五段式缺段、模板缺配等，属代码缺陷而非数据问题。"""


__all__ = ["RuleImplementationError"]
