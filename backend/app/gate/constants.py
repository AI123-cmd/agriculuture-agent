"""闸门具名常量（T2-34）。

降级文案与强制语气模式都属于**闸门定义的内容**而非运营可调参数：降级文案若允许模型生成，
就等于给了模型一条绕过闸门的输出通道（技术方案 8.1"不调用大模型，因此每次判定都可复现"）；
强制语气模式若散落在规则里，两个集合会漂移，出现"这条拦了、那条没拦"的不一致。
"""

import re

# degrade / block 两种裁定的对外统一文案。产品说明书 6.2：校验不通过时输出降级为
# "建议联系当地农技站"，而不是修改后输出。block 也用同一份文案，因为农户不需要知道
# "是硬红线还是地区不匹配"，两者的正确指引都是问本地农技站，差别只在内部审计与工单。
DEGRADE_OUTPUT_TEXT = (
    "这份建议还需要当地农技站把关。建议你带着地块情况和已用的药，联系本地农技站做一次现场确认后再用药。"
)

# 强制命令语气模式：命中即 warn。仅收录明确的命令式表达，刻意不收录"必须"——
# "必须等待 7 天"这类在安全提示中是正确表述，收进来会造成大量误报。
IMPERATIVE_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(r"立即(?:大量)?(?:施用|喷洒|使用|灌)"),
    re.compile(r"务必(?:马上|立刻|立即)"),
    re.compile(r"直接(?:用|打|喷)(?:就|即可)"),
    re.compile(r"不用(?:问|管|考虑)"),
    re.compile(r"照做(?:就行|即可)"),
)


__all__ = ["DEGRADE_OUTPUT_TEXT", "IMPERATIVE_PATTERNS"]
